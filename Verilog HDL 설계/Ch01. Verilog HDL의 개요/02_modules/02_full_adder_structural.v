// ============================================================================
// MODULE BASICS 2: STRUCTURAL HIERARCHY
//
// One full adder can be built from two half adders and an OR gate.
// The half_adder module is declared in 01_half_adder.v.
// Each use of half_adder creates an instance with its own connections.
//
// Named port mapping uses .port_name(signal_name).
// Example: .a(a) connects a child port named a to a parent signal named a.
// Internal wires join child instances inside the parent module.
// Hierarchy separates reusable logic blocks from their composition.
// ============================================================================

`timescale 1ns/1ps

module full_adder_structural (
    input  wire a,
    input  wire b,
    input  wire cin,
    output wire sum,
    output wire cout
);
    // Intermediate sum from the first half adder.
    wire sum_ab;
    // Carry generated by the first half adder.
    wire carry_ab;
    // Carry generated when adding cin.
    wire carry_cin;

    // First child instance adds a and b.
    half_adder u_ha0 (
        .a(a),
        .b(b),
        .sum(sum_ab),
        .carry(carry_ab)
    );

    // Second child instance adds sum_ab and cin.
    half_adder u_ha1 (
        .a(sum_ab),
        .b(cin),
        .sum(sum),
        .carry(carry_cin)
    );

    // Combine both intermediate carry signals.
    assign cout = carry_ab | carry_cin;
endmodule
